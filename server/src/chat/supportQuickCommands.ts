const byId = new Map(SUPPORT_QUICK_COMMANDS.map((c) => [c.id, c]));

export function getSupportQuickCommand(id: string): SupportQuickCommand | null {
  return byId.get(id as SupportQuickCommandId) ?? null;
}

export function listSupportQuickCommandsPublic() {
  return SUPPORT_QUICK_COMMANDS.map(({ id, label, userPrompt }) => ({ id, label, userPrompt }));
}
